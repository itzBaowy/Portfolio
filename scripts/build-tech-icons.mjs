import { copyFile, mkdir, writeFile } from "node:fs/promises";
import * as icons from "simple-icons";
import { format, resolveConfig } from "prettier";

// Only selected SVG paths enter the app; the complete catalog stays in build tooling.
const brands = {
  TypeScript: ["typescript", "#5da9ff"],
  "JavaScript ES6+": ["javascript", "#f7df1e"],
  "Next.js": ["nextdotjs", "#f5f5f7"],
  React: ["react", "#61dafb"],
  Electron: ["electron", "#8fcbd6"],
  Redux: ["redux", "#b18be9"],
  "Tailwind CSS": ["tailwindcss", "#38c9e3"],
  NestJS: ["nestjs", "#fb5b7d"],
  Express: ["express", "#d2d5df"],
  PostgreSQL: ["postgresql", "#7ca0f3"],
  MySQL: ["mysql", "#7bb7dd"],
  MongoDB: ["mongodb", "#75cc7b"],
  Redis: ["redis", "#ff6b61"],
  Elasticsearch: ["elasticsearch", "#58cfde"],
  Docker: ["docker", "#55b7ff"],
  "GitHub Actions": ["githubactions", "#78aaff"],
  Jenkins: ["jenkins", "#ed8c80"],
  Claude: ["claude", "#e6a183"],
  Git: ["git", "#fa8069"],
  Figma: ["figma", "#bd9aff"],
  Cursor: ["cursor", "#eceef6"],
};
const symbols = {
  WebSocket: { kind: "symbol", symbol: "socket", color: "#79d7c8" },
  "CI/CD": { kind: "symbol", symbol: "workflow", color: "#a8a2ff" },
  "AWS Lightsail": { kind: "symbol", symbol: "cloud", color: "#f1b76b" },
  OpenAI: { kind: "symbol", symbol: "assistant", color: "#82cfb1" },
  Codex: { kind: "symbol", symbol: "terminal", color: "#a3b3ff" },
  "Google Stitch": { kind: "symbol", symbol: "design", color: "#9eabff" },
};
const visuals = {};
const sources = [];
for (const [name, [slug, color]] of Object.entries(brands)) {
  const icon = Object.values(icons).find((entry) => entry.slug === slug);
  if (!icon) throw new Error(`Missing Simple Icons mark: ${slug}`);
  visuals[name] = { kind: "brand", color, path: icon.path };
  sources.push({
    name,
    slug,
    source: icon.source,
    guidelines: icon.guidelines,
    license: icon.license,
  });
}
Object.assign(visuals, symbols);
const types = `import type { Technology } from "./skills";

export type TechnologyVisual =
  | { kind: "brand"; color: string; path: string }
  | { kind: "symbol"; color: string; symbol: "socket" | "workflow" | "cloud" | "assistant" | "terminal" | "design" };

`;
const formatOptions = await resolveConfig("src/data/technology-visuals.ts");
await writeFile(
  "src/data/technology-visuals.ts",
  await format(
    `// Generated by npm run icons. SVG paths: Simple Icons 16.34.0; see docs/icon-sources.json.\n${types}export const technologyVisuals = ${JSON.stringify(visuals, null, 2)} satisfies Record<Technology, TechnologyVisual>;\n`,
    { ...formatOptions, parser: "typescript" },
  ),
);
await mkdir("docs/licenses", { recursive: true });
await copyFile("node_modules/simple-icons/LICENSE.md", "docs/licenses/simple-icons.md");
await writeFile(
  "docs/icon-sources.json",
  `${JSON.stringify({ package: "simple-icons@16.34.0", icons: sources }, null, 2)}\n`,
);
console.log(
  `Generated ${Object.keys(visuals).length} technology visuals (${sources.length} brand marks).`,
);
